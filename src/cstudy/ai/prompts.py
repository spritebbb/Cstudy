# ============ 12. 找知识点之间的关系（知识图谱的连线）============

POINT_RELATION_SYSTEM = """你在给一份 C 语言考试大纲的知识点找**关系**。
这些关系会画成一张知识图谱，用户照着它决定先补哪儿、哪块没打通。

用户会给你考纲里的全部知识点，每个都带所属章节。

**关系只有三种，别的不认：**

- `prereq`：写 `A → B` 表示**必须先学懂 A，才学得懂 B**。
  有方向，**别写反**——写反了用户就会照着一条错误的顺序去复习。
- `confuse`：A 和 B **容易记混**，考试最爱在这儿设陷阱。
  没有方向，写哪边在前都行。
- `related`：A 和 B 有联系，但谈不上谁先谁后。没有方向。

**最重要的一条：只给有把握的，宁可少给。**

这张图的作用是让人一眼看出结构。混进一条假关系，用户就会照着一条不存在的
学习路径去复习——**比少几条线糟得多**。具体地：

- **别只因为两个知识点在同一章就连线**。要有具体理由：谁先谁后、谁是谁的基础、
  哪里容易混。说不出来就别写。**但同章内的关系完全可以是好关系**——
  `break` 与 `continue`、`i++` 与 `++i` 都在同一章里，而它们恰恰是最该连的
- `related` 是最弱的一档，**别拿它凑数**。想不出具体联系就别写
- 每条都要能说清**为什么**。理由写不出具体内容的，说明这条关系其实没想清楚，
  删掉它
- 反过来，下面这几类**非常值得写**（都是 C 语言里真实存在的依赖）：
  - 语法结构之间的递进：if → else-if → switch；while → do-while → for
  - 数组 → 指针处理数组 → 指针数组；函数 → 递归 → 函数指针
  - 结构体 → 用指针处理链表；文件 → 文件读写 → 文件定位
  - 极易混淆的对子：`break` 与 `continue`；`i++` 与 `++i`；
    数组名与指针变量；`=` 与 `==`；结构体与共用体

只能写清单里**一字不差**的知识点名字。不要自己造名字、不要改写、
不要写章节名——写了也没用，清单里没有的一律会被丢掉。

只输出 JSON，不要输出任何其他文字：
{
  "relations": [
    {
      "from": "知识点名字（从清单里原样抄）",
      "to": "知识点名字（从清单里原样抄）",
      "kind": "prereq 或 confuse 或 related",
      "reason": "一句话说清为什么。要具体，别写'都跟指针有关'这种空话"
    }
  ]
}
"""


def point_relation_user_prompt(grouped: dict[str, list[str]], limit: int) -> str:
    """把整份考纲按章列给模型。`grouped` 是 {章名: [知识点名字]}。"""
    parts = []
    for chapter, names in grouped.items():
        parts.append(f"【{chapter}】")
        parts.extend(f"  - {name}" for name in names)
    body = "\n".join(parts)
    total = sum(len(names) for names in grouped.values())
    return (
        f"===== 考纲知识点（共 {total} 个，按章列出）=====\n{body}\n\n"
        f"请找出它们之间的关系，**最多 {limit} 条**，按重要性从高到低给。\n"
        "记住：只写你有把握的，理由要具体，名字要一字不差。"
    )
